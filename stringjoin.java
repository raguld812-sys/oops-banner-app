public class stringjoin {

    public static void main(String[] args) {

        System.out.println(string.join("   ***   " + "   ***   " + "*********" + "*********"));
        System.out.println(string.join("  ** **  " + "  ** **  " + "*********" + "*********"));
        System.out.println(string.join(" **   ** " + " **   ** " + "***   ** " + "**      "));
        System.out.println(string.join(" **   ** " + " **   ** " + "******** " + "********"));
        System.out.println(string.join(" **   ** " + " **   ** " + "******** " + "********"));
        System.out.println(string.join("  ** **  " + "  ** **  " + "***      " + "**      "));
        System.out.println(string.join("   ***   " + "   ***   " + "***      " + "********"));
        
    }

}